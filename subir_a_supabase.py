"""Sube la base local (data/prototipo.db) a PostgreSQL en Supabase.

Uso:
    python3 generar_datos.py        # (si aún no existe la base local)
    python3 subir_a_supabase.py

Lee DATABASE_URL de .streamlit/secrets.toml (o de la variable de entorno).
ATENCIÓN: borra y reemplaza las tablas que haya en Supabase.
"""
import os
import sqlite3
import sys
import tomllib
from pathlib import Path

import psycopg

BASE = Path(__file__).parent
LOCAL = BASE / "data" / "prototipo.db"
# Orden: primero las tablas de las que dependen otras.
TABLAS = ["usuario", "sujeto", "procesamiento_previo", "estudio_imagen", "decalcificacion",
          "cambio_edta", "bloque", "placa", "resultado_placa", "imagen_placa", "evento"]


def url_base():
    if os.environ.get("DATABASE_URL"):
        return os.environ["DATABASE_URL"]
    secretos = BASE / ".streamlit" / "secrets.toml"
    if secretos.exists():
        return tomllib.loads(secretos.read_text(encoding="utf-8")).get("DATABASE_URL")
    return None


def esquema_postgres():
    # Misma estructura que SQLite; solo cambia cómo se numeran los id automáticos.
    sql = (BASE / "esquema.sql").read_text(encoding="utf-8")
    return sql.replace("INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


def main():
    url = url_base()
    if not url:
        sys.exit("Falta DATABASE_URL en .streamlit/secrets.toml")
    if not LOCAL.exists():
        sys.exit("No existe data/prototipo.db. Ejecuta primero: python3 generar_datos.py")
    if "--si" not in sys.argv:
        if input("Esto BORRA los datos en Supabase y los reemplaza. Escribe SI para seguir: ") != "SI":
            sys.exit("Cancelado.")

    local = sqlite3.connect(LOCAL)
    with psycopg.connect(url, prepare_threshold=None) as pg:
        for t in reversed(TABLAS):
            pg.execute(f"DROP TABLE IF EXISTS {t} CASCADE")
        pg.execute(esquema_postgres())
        for t in TABLAS:
            cur = local.execute(f"SELECT * FROM {t}")
            columnas = [d[0] for d in cur.description]
            filas = cur.fetchall()
            if filas:
                marcas = ", ".join(["%s"] * len(columnas))
                with pg.cursor() as c:
                    c.executemany(f"INSERT INTO {t} ({', '.join(columnas)}) VALUES ({marcas})", filas)
            # Los id automáticos deben seguir después del último cargado.
            if local.execute(f"SELECT type FROM pragma_table_info('{t}') WHERE name = 'id'").fetchone()[0] == "INTEGER":
                pg.execute(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), "
                           f"COALESCE((SELECT MAX(id) FROM {t}), 0) + 1, false)")
            print(f"{t:22} {len(filas)} filas")
    print("\nListo: datos subidos a Supabase.")


if __name__ == "__main__":
    main()
